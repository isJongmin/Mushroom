"""Export attachment points from the same skeleton/camera as the shipped avatar PNGs."""
import json
import sys
from pathlib import Path
import numpy as np
import model
from vox import view_matrix

frames = ['front', 'front_b', 'side', 'walk0', 'walk1', 'walk2', 'walk3', 'back', 'jump', 'fall', 'prone', 'attack0', 'attack1']
hands = []
for frame in frames:
    transforms = model.bone_xf(model.pose_frame(frame))
    camera = view_matrix({'front': -25, 'front_b': -25, 'back': 160}.get(frame, 62), 8 if frame == 'prone' else 10)
    anchors = {}
    for key, sign in [('N', -1), ('F', 1)]:
        rotation, translation = transforms['arm%+d' % sign]
        centre = model.girth({'bone': 'arm%+d' % sign, 'c': (0, -14.6, .3), 'h': (2.25, 2.2, 2.3)})['c']
        point = camera @ (translation + rotation @ np.array(centre))
        anchors[key] = [round(float(point[0]) * 1.82 / 1.5, 3), round(float(-point[1]) * 1.82 / 1.5, 3)]
    hands.append(anchors)
source = '// Generated by assets/_src/voxel/export_hand_anchors.py from the shipped voxel skeleton/camera.\nexport const AVATAR_HANDS=Object.freeze(' + json.dumps(hands, separators=(',', ':')) + ');\nexport const handAnchor=frame=>AVATAR_HANDS[Math.max(0,Math.min(12,frame|0))];\n'
target = Path(__file__).resolve().parents[3] / 'src/client/game/avatar-hand-anchors.js'
if '--check' in sys.argv:
    assert target.read_text() == source, 'Hand anchors do not match the voxel skeleton'
    print('PASS all 26 hand anchors match the shipped voxel skeleton and projection')
else:
    target.write_text(source)
